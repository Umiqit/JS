// Задание 3
// Создан массив, содержащий названия школьных предметов.
// Метод slice(...) выделяет из него два массива:
// к первому относятся предметы из раздела точных наук, ко второму — гуманитарных.
// Исполняющий скрипт оформлен в виде отдельной функции showSubjects(),
// описанной в разделе <head> и вызванной в разделе <body>.

function showSubjects() {
    var subjects = new Array("математика", "физика", "химия",   // точные науки
                             "литература", "история", "русский язык"); // гуманитарные

    var exact = subjects.slice(0, 3);   // предметы из раздела точных наук
    var humanities = subjects.slice(3); // предметы из раздела гуманитарных наук

    document.write("Все предметы: " + subjects + "<br>");
    document.write("Точные науки: " + exact + "<br>");
    document.write("Гуманитарные науки: " + humanities + "<br>");
}
