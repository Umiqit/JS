// Задание 8
// Сценарий преобразует символы фамилии в прописные символы.
// Если указать возраст, меньший 18 лет, сценарий сделает его равным нулю.
// Если после заполнения анкеты нажать кнопку Complete, на экране появится
// диалоговая панель, отображающая содержимое отдельных полей формы.
// Кнопка Reset устанавливает поля в исходное состояние.

function processForm() {
    var f = document.anketa;

    // символы фамилии преобразуются в прописные символы
    f.surname.value = f.surname.value.toUpperCase();

    // если возраст меньше 18 лет — делаем его равным нулю
    if (parseInt(f.age.value) < 18) {
        f.age.value = 0;
    }

    // диалоговая панель с содержимым отдельных полей формы
    alert("Фамилия: " + f.surname.value + "\n" +
          "Имя: " + f.name.value + "\n" +
          "Телефон: " + f.phone.value + "\n" +
          "Возраст: " + f.age.value);
}
