// Задание 9
// Проверка ввода имени пользователя и адреса электронной почты
// (адрес проверяется на наличие «@» и «.»).
// Для отправки данных используется обработчик событий onSubmit.
// Если есть ошибка при вводе данных об этом выдается сообщение
// и после нажатия кнопки «OK», поле с ошибкой находится в фокусе.

function checkForm() {
    var f = document.mailForm;

    // проверка ввода имени пользователя
    if (f.userName.value == "") {
        alert("invalid User Name");
        f.userName.focus(); // поле с ошибкой находится в фокусе
        return false;
    }

    // проверка адреса электронной почты на наличие «@» и «.»
    if (f.userEmail.value.indexOf("@") == -1 ||
        f.userEmail.value.indexOf(".") == -1) {
        alert("invalid E-Mail");
        f.userEmail.focus(); // поле с ошибкой находится в фокусе
        return false;
    }

    return true; // ошибок нет — данные отправляются
}
